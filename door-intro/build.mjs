// Builds every DoorIntro distribution from src/door-intro.js.
//   node door-intro/build.mjs
// Outputs:
//   dist/door-intro(.min).js            brand-neutral build
//   dist/opendoors/door-intro(.min).js  Open Doors Financial Group preset baked in
//   wordpress/door-intro/assets/door-intro.js   (minified, neutral)
//   react/door-intro.js                 core imported by react/DoorIntro.jsx
//   webflow/door-intro-embed.html       paste-in embed (minified, Open Doors preset)
//   ../site/door-intro.js               static site integration (minified, Open Doors preset)
// Minification uses terser when installed (npm install); otherwise the
// readable source is copied instead.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, 'src/door-intro.js'), 'utf8');
const MARKER = '{} /*@build-defaults*/';
if (!src.includes(MARKER)) throw new Error('build-defaults marker missing from src/door-intro.js');

// Where the founders portrait is expected on the Open Doors site.
export const OPENDOORS_DEFAULTS = {
  preset: 'opendoors',
  imageUrl: '/images/door-intro/arrington-founders.jpg'
};

function withDefaults(defaults) {
  return src.replace(MARKER, JSON.stringify(defaults) + ' /*@build-defaults*/');
}

function write(rel, content) {
  const out = join(here, rel);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, content);
  console.log(`wrote ${rel} (${(Buffer.byteLength(content) / 1024).toFixed(1)} KB)`);
}

let minify = async (code) => code;
try {
  const { minify: terser } = await import('terser');
  minify = async (code) => (await terser(code, { compress: true, mangle: true, format: { comments: /^!/ } })).code + '\n';
} catch {
  console.warn('terser not installed; writing unminified files (run npm install in door-intro/)');
}

const neutral = src;
const opendoors = withDefaults(OPENDOORS_DEFAULTS);
const neutralMin = await minify(neutral);
const opendoorsMin = await minify(opendoors);

write('dist/door-intro.js', neutral);
write('dist/door-intro.min.js', neutralMin);
write('dist/opendoors/door-intro.js', opendoors);
write('dist/opendoors/door-intro.min.js', opendoorsMin);
write('wordpress/door-intro/assets/door-intro.js', neutralMin);
write('react/door-intro.js', neutral);
if (existsSync(join(here, '../site'))) write('../site/door-intro.js', opendoorsMin);

const prepaint = readFileSync(join(here, 'snippets/head-prepaint.html'), 'utf8');
const embed = `<!--
  DoorIntro — Webflow embed (generated by door-intro/build.mjs; do not edit by hand).

  1. Project Settings → Custom Code → Head Code: paste the PRE-PAINT block.
  2. Project Settings → Custom Code → Footer Code: paste the CONFIG + SCRIPT block.
  3. Upload the founders portrait to Webflow Assets, copy its URL, and set imageUrl below.
  4. Publish. Test with ?doorintro=1 to force the intro.
-->

<!-- ============ PRE-PAINT (Head Code) ============ -->
${prepaint.trim()}

<!-- ============ CONFIG + SCRIPT (Footer Code) ============ -->
<script>
  window.DoorIntroConfig = {
    preset: 'opendoors',
    imageUrl: 'https://YOUR-WEBFLOW-ASSET-URL/arrington-founders.jpg',
    logoUrl: '',            // optional: Webflow asset URL of the logo (SVG/PNG)
    playMode: 'session'     // session | once | always | manual
  };
</script>
<script>
${neutralMin.trim()}
</script>
`;
write('webflow/door-intro-embed.html', embed);
